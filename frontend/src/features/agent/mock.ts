// FAKE AGENT (see lib/api/mockDb.ts and ./mockScript.ts).
// The script's steps "appear" one by one as time goes by, imitating
// the backend, which runs the agent in the background and records each AgentStep.
import { fakeImage } from "@/features/images/fakeImage";
import { nowIso, latency, mockDb, type MockRun } from "@/lib/api/mockDb";
import { createScript } from "./mockScript";
import type { AgentService } from "./service";
import type { AgentRun } from "./types";

/** Time between one step and the next on screen (shorter than the "real" durations). */
const INTERVAL_MS = 900;

/** Creates the post draft when a creation run ends. */
function finish(exec: MockRun): MockRun {
  let postId = exec.post_id;
  const draft = exec.script.draft;
  if (draft && !postId) {
    const now = nowIso();
    postId = crypto.randomUUID();
    // The image generated by the agent goes into the project library and the draft
    const prompt = exec.script.steps.find((p) => p.tool === "generate_image")
      ?.arguments.prompt;
    const imageId = crypto.randomUUID();
    mockDb.images.insert({
      id: imageId,
      project_id: exec.project_id,
      content_type: "image/svg+xml",
      description: typeof prompt === "string" ? prompt : null,
      url: fakeImage(imageId),
      created_at: now,
      updated_at: now,
    });
    mockDb.posts.insert({
      id: postId,
      subject_id: draft.subject_id,
      title: draft.title,
      // One variation per requested network, with the generated image.
      // The agent only saves drafts.
      variations: (draft.networks.length
        ? draft.networks
        : (["linkedin"] as const)
      ).map((network) => ({
        id: crypto.randomUUID(),
        network,
        format: "single",
        content: draft.text,
        status: "draft",
        expected_date: null,
        image_ids: [imageId],
      })),
      created_at: now,
      updated_at: now,
    });
  }
  return mockDb.runs.replace({
    ...exec,
    post_id: postId,
    finished: true,
  });
}

/** Builds the API response from the time elapsed since the start. */
function materialize(record: MockRun): AgentRun {
  const total = record.script.steps.length;
  const elapsed = Date.now() - new Date(record.started_at).getTime();

  let exec = record;
  if (!exec.finished && elapsed >= total * INTERVAL_MS + 400) {
    exec = finish(exec);
  }

  const visible = exec.finished
    ? total
    : Math.min(total, Math.floor(elapsed / INTERVAL_MS));

  const totalDuration = exec.script.steps.reduce(
    (sum, p) => sum + (p.duration_ms ?? 0),
    0,
  );

  // Parallel calls (e.g. adapting for LinkedIn and for X) count as one iteration
  const seenSteps = exec.script.steps.slice(0, visible);
  const iterations = seenSteps.filter((p) => !p.parallel).length;

  return {
    id: exec.id,
    project_id: exec.project_id,
    mode: exec.mode,
    request: exec.request,
    status: exec.finished ? exec.script.statusFinal : "running",
    response: exec.finished ? exec.script.response : null,
    post_id: exec.finished ? exec.post_id : null,
    iterations,
    steps: seenSteps.map((p, i) => ({
      tool: p.tool,
      arguments: p.arguments,
      result_summary: p.result_summary,
      duration_ms: p.duration_ms,
      error: p.error,
      id: `${exec.id}-passo-${i + 1}`,
      step_number: i + 1,
    })),
    started_at: exec.started_at,
    finished_at: exec.finished
      ? new Date(
          new Date(exec.started_at).getTime() + totalDuration,
        ).toISOString()
      : null,
  };
}

export const agentMock: AgentService = {
  async startRun({ project_id, mode, request }) {
    await latency();
    const project = mockDb.projects.find(project_id, "Projeto");
    const subjects = mockDb.subjects
      .todos()
      .filter((a) => a.project_id === project_id);
    // Uses the subject named in the request; otherwise, the project's first one
    const subject =
      subjects.find((a) =>
        request.toLowerCase().includes(a.name.toLowerCase()),
      ) ??
      subjects[0] ??
      null;
    const documents = mockDb.documents
      .todos()
      .filter((d) => d.project_id === project_id && d.status === "ready")
      .map((d) => d.name);

    const record = mockDb.runs.insert({
      id: crypto.randomUUID(),
      project_id,
      mode,
      request,
      started_at: nowIso(),
      script: createScript({
        mode,
        request,
        project,
        subject: subject && { id: subject.id, name: subject.name },
        documents,
      }),
      post_id: null,
      finished: false,
    });
    return materialize(record);
  },

  async list(projectId) {
    await latency();
    return mockDb.runs
      .todos()
      .filter((e) => e.project_id === projectId)
      .map(materialize)
      .sort((a, b) => b.started_at.localeCompare(a.started_at));
  },

  async get(id) {
    await latency();
    return materialize(mockDb.runs.find(id, "Execução"));
  },
};
